// Package apiproto holds the neutral JSON wire types shared by the `af` CLI
// (api/) and the daemon-hosted HTTP server (daemon/). It deliberately depends on
// neither: api/ imports daemon/ for its RPC client wrappers, so the daemon
// cannot import api/, and both instead import this leaf package. Keeping the
// Envelope definition here — rather than duplicated in each — is what guarantees
// the CLI's `--json` output and the HTTP server's responses stay byte-for-byte
// identical (#1029 PR 4).
package apiproto

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
)

// Envelope is the additive JSON wrapper shared by the CLI and the daemon-hosted
// HTTP server. A success carries the payload in Data with Error nil; a failure
// carries a nil Data and a populated Error. Both members always serialize (no
// omitempty) so consumers can branch on `error === null` without a presence
// check:
//
//	success: {"data": <payload>, "error": null}
//	failure: {"data": null, "error": {"message": "<msg>"}}
//
// On the CLI it is NEW infrastructure: today's commands still emit the bare
// payload by default, and the envelope is only produced on the explicit opt-in
// path (the --json flag), so no existing command's stdout/stderr bytes change.
// The HTTP server always emits it.
type Envelope struct {
	Data  any            `json:"data"`
	Error *EnvelopeError `json:"error"`
}

// EnvelopeError is the error member of an Envelope. Message is a human-readable
// description. Code is an optional machine-readable outcome; omitting it keeps
// ordinary failure envelopes byte-for-byte compatible with older clients.
type EnvelopeError struct {
	Message string `json:"message"`
	Code    string `json:"code,omitempty"` // Clients preserve this for retry safety.
	// DaemonRejected marks an ordinary error generated by the daemon HTTP
	// handler. Unmarked intermediary errors do not establish mutation refusal.
	DaemonRejected bool `json:"daemon_rejected,omitempty"`
	// StoredID is the id of the record a COMMITTED mutation stored, for a caller
	// that did not choose it (a sandbox credential's task add: the daemon mints
	// the id). An error carries no response body, so without this a caller whose
	// add committed but whose follow-up failed could not address what exists.
	StoredID string `json:"stored_id,omitempty"`
}

// ErrorCodeMutationCommitted says the requested mutation reached durable
// storage before a later, non-transactional follow-up failed. A caller must
// still surface the failure, but must not retry the mutation as though it never
// happened.
const ErrorCodeMutationCommitted = "mutation_committed"

// ErrorCodeResourceExhausted says the server verified a kernel resource limit
// — a full filesystem, quota, fd table, memory or PID ceiling — behind the
// failure. The errno itself cannot cross the wire as an error identity, so
// the code carries the class; a client that reconstructs
// ErrRemoteResourceExhausted lets errors.Is-based policy see it (#5295 review).
const ErrorCodeResourceExhausted = "resource_exhausted"

// ErrRemoteResourceExhausted is the client-side sentinel joined into an error
// decoded from a failure envelope carrying ErrorCodeResourceExhausted. The
// server only emits that code after verifying a resource errno in the real
// failure chain, so errors.Is(err, ErrRemoteResourceExhausted) on the client
// means exactly what the verified errno meant on the server (#5295 review).
var ErrRemoteResourceExhausted = errors.New("remote reported kernel resource exhaustion")

// ErrorCodeDeadlineExceeded says the operation died on a bounded wait INSIDE
// the operation — for the archive RPC, the git push's own network deadline
// within the sandbox — distinct from the transport's own timeout, which the
// client already sees as context.DeadlineExceeded. A deadline's errors.Is
// identity cannot cross the wire either, so the code carries that class: the
// client reconstructs context.DeadlineExceeded and the preserve call site's
// bounded-deadline arm reads a stalled origin as the environmental stall it
// is, instead of charging it structural until the budget gives up (#5295
// review).
const ErrorCodeDeadlineExceeded = "deadline_exceeded"

// ErrorCodeTabGone says the failure is specifically "the stable tab id names no
// live tab" (session.ErrTabGone) — the error identity cannot cross the wire as
// a sentinel, so the code carries it. A bare 404 is ambiguous: the same status
// answers an unknown ROUTE on an older server, and a client that maps 404 to
// gone outright would misreport "the route predates this server" as "the tab is
// dead" (#5571 W4.3). With the code, a remote client reconstructs ErrTabGone
// exactly as it does the resource/deadline classes above.
const ErrorCodeTabGone = "tab_gone"

// ErrorCodeProjectRebound says a RebindProject request carrying expected_root
// was refused because the project's recorded root no longer matched it:
// another rebind landed first (#4822). Nothing was written; the caller should
// re-read the registry and let the user decide again.
const ErrorCodeProjectRebound = "project_rebound"

// Success wraps a payload as a successful Envelope (Error nil).
func Success(data any) Envelope {
	return Envelope{Data: data, Error: nil}
}

// Failure wraps a message as a failed Envelope (Data nil).
func Failure(msg string) Envelope {
	return Envelope{Data: nil, Error: &EnvelopeError{Message: msg}}
}

// FailureWithCode wraps a failure with an additive machine-readable outcome.
// Older clients ignore Code and retain the existing human-readable error.
func FailureWithCode(msg, code string) Envelope {
	return Envelope{Data: nil, Error: &EnvelopeError{Message: msg, Code: code}}
}

// MarshalIndented is the single JSON-encoding primitive the CLI and HTTP output
// paths share so bare and enveloped output format identically (two-space
// indent).
func MarshalIndented(v any) ([]byte, error) {
	return json.MarshalIndent(v, "", "  ")
}

// WriteEnvelope encodes env and writes it, newline-terminated, to w. It is the
// shared write path the CLI's opt-in --json output and the daemon HTTP server
// both reuse, keeping their responses byte-for-byte consistent.
func WriteEnvelope(w io.Writer, env Envelope) error {
	data, err := MarshalIndented(env)
	if err != nil {
		return err
	}
	_, err = fmt.Fprintln(w, string(data))
	return err
}
